#!/usr/bin/env python3
"""Knowledge-base tooling for flatline-shopify-kit.

  kb.py index          regenerate knowledge/INDEX.md from entry frontmatter
  kb.py index --check  exit 1 if INDEX.md is stale (used by the pre-commit hook)
  kb.py lint [files]   validate schema + guardrails (no URLs, secrets, client names in bodies)
"""
import os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KB = os.path.join(ROOT, "knowledge")
FIELDS = ["symptom", "root_cause", "fix", "affected_areas", "tags", "date",
          "author", "clients_generalized_from", "severity"]
SEVERITIES = {"low", "medium", "high"}

def entries():
    return sorted(p for p in glob.glob(f"{KB}/*/*.md"))

def parse(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        return None, text
    fm = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        if _ and re.match(r"^[a-z_]+$", k):
            fm[k.strip()] = v.strip()
    return fm, m.group(2)

def tags_of(fm):
    return [t.strip().strip("\"'") for t in fm.get("tags", "").strip("[]").split(",") if t.strip()]

HEADER = """# Knowledge index

Generated by `scripts/kb.py index` from each entry's frontmatter — do not edit rows by
hand. `/log-fix` runs it after writing an entry, and the pre-commit hook fails if this
file is stale.

| Category | Entry | Tags | Severity |
|---|---|---|---|
"""

def build_index():
    rows = []
    for p in entries():
        fm, _ = parse(p)
        if not fm:
            continue
        cat, slug = p.split("/")[-2], os.path.basename(p)[:-3]
        rows.append((fm.get("date", ""), f"| {cat} | [{slug}]({cat}/{slug}.md) | {', '.join(tags_of(fm))} | {fm.get('severity','')} |"))
    return HEADER + "\n".join(r for _, r in sorted(rows)) + "\n"

def client_names():
    names = set()
    for p in entries():
        fm, _ = parse(p)
        if fm:
            names |= {c.strip().strip("\"'").lower() for c in fm.get("clients_generalized_from", "").strip("[]").split(",") if c.strip()}
    dev = os.path.expanduser("~/Developer")
    if os.path.isdir(dev):
        for d in os.listdir(dev):
            if os.path.isdir(f"{dev}/{d}") and d not in ("fa-harness", "flatline", "node_modules") and not d.startswith("."):
                names.add(d.lower())
    return {n for n in names if len(n) > 3}

BAD = [
    (r"https?://", "live URL"),
    (r"[a-z0-9-]+\.myshopify\.com", "myshopify domain"),
    (r"\bshp(at|ca|pa|ss)_[A-Za-z0-9]+", "Shopify token"),
    (r"\b(sk|pk)_(live|test)_[A-Za-z0-9]+", "API key"),
    (r"(?i)\b(api[_-]?key|secret|password)\s*[:=]\s*\S{8,}", "credential assignment"),
    (r"[\w.+-]+@[\w-]+\.[\w.]+", "email address"),
]

def lint(paths):
    errs, names = [], client_names()
    for p in paths:
        rel = os.path.relpath(p, ROOT)
        fm, body = parse(p)
        if fm is None:
            errs.append(f"{rel}: missing YAML frontmatter"); continue
        for f in FIELDS:
            if f not in fm or not fm[f]:
                errs.append(f"{rel}: missing frontmatter field '{f}'")
        if fm.get("severity") and fm["severity"] not in SEVERITIES:
            errs.append(f"{rel}: severity must be low|medium|high")
        if fm.get("date") and not re.match(r"^\d{4}-\d{2}-\d{2}$", fm["date"]):
            errs.append(f"{rel}: date must be YYYY-MM-DD")
        if not re.search(r"(?m)^## .*(Symptom|Root cause|Diagnos)", body):
            errs.append(f"{rel}: body needs a '## Symptom' / '## Root cause' (or '## Diagnosing…') section")
        if not re.search(r"(?m)^## Fix", body):
            errs.append(f"{rel}: body needs a '## Fix' section")
        whole = open(p, encoding="utf-8").read()
        for rx, label in BAD:
            if re.search(rx, whole):
                errs.append(f"{rel}: contains {label}")
        generalized_free = re.sub(r"(?m)^clients_generalized_from:.*$", "", whole).lower()
        for n in names:
            if re.search(rf"\b{re.escape(n)}\b", generalized_free):
                errs.append(f"{rel}: names client '{n}' outside clients_generalized_from")
    return errs

if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "index":
        out, path = build_index(), f"{KB}/INDEX.md"
        if "--check" in sys.argv:
            if open(path).read() != out:
                print("knowledge/INDEX.md is stale — run: scripts/kb.py index"); sys.exit(1)
            print("INDEX.md up to date")
        else:
            open(path, "w").write(out); print(f"wrote {path} ({len(entries())} entries)")
    elif cmd == "lint":
        files = [os.path.abspath(a) for a in sys.argv[2:]] or entries()
        errs = lint(files)
        print("\n".join(errs) if errs else f"lint OK ({len(files)} entries)")
        sys.exit(1 if errs else 0)
    else:
        print(__doc__); sys.exit(2)
